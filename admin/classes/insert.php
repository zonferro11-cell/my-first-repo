// Подключаем базу данных (файл лежит на две папки выше)
require_once '../../conn.php';

// Берём название класса из формы
$title = $_POST['title'];

// Экранируем кавычки, чтобы название вида 10'А не сломало SQL-запрос (защита от SQL-инъекций)
$title = mysqli_real_escape_string($conn, $title);

// Собираем SQL-запрос. Текст в SQL пишется в одинарных кавычках '...'
$query = "INSERT INTO classes (title) VALUES ('$title')";

// Выполняем запрос; если ошибка — показываем её и останавливаем скрипт
mysqli_query($conn, $query) or die("Ошибка: " . mysqli_error($conn));

// Перенаправляем браузер обратно на список классов
header("Location: ../index.php?page=classes");
